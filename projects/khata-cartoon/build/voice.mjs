#!/usr/bin/env node
// voice.mjs — make every dialogue line of story/lines.json with the offline Piper voice, then measure it.
//
//   node build/voice.mjs            (from the project folder; unchanged lines are skipped)
//
// Writes assets/voice/<id>.wav (48 kHz mono, -16 LUFS, 0.25 s lead silence — tools/bn-tts.mjs), story/voice.json
// (durations) and assets/voice/lipsync.js: window.HKLip[id] = { d: seconds, env: "0379…" } — one digit per frame at
// 30 fps, the mouth opening 0..9. The opening follows the line's own loudness, normalised per line (its quiet 20th
// percentile → 0, its loud 95th → 9) so the dips between syllables close the mouth and the flaps are visible.

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const TTS = path.resolve(ROOT, "..", "..", "tools", "bn-tts.mjs");
const FPS = 30, RATE = 48000;
const story = JSON.parse(readFileSync(path.join(ROOT, "story", "lines.json"), "utf8"));
const outDir = path.join(ROOT, "assets", "voice");
mkdirSync(outDir, { recursive: true });

function pcm(file) {
  const r = spawnSync("ffmpeg", ["-v", "error", "-i", file, "-ac", "1", "-ar", String(RATE), "-f", "f32le", "-"], { maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new Error(`ffmpeg could not read ${file}`);
  return new Float32Array(r.stdout.buffer, r.stdout.byteOffset, Math.floor(r.stdout.length / 4));
}
function envelope(x) {
  const hop = RATE / FPS, db = [];
  for (let i = 0; i + hop <= x.length; i += hop) {
    let s = 0;
    for (let k = 0; k < hop; k++) s += x[i + k] * x[i + k];
    db.push(10 * Math.log10(s / hop + 1e-12));
  }
  const speech = db.filter((v) => v > -50).sort((a, b) => a - b);
  if (!speech.length) return db.map(() => 0);
  const lo = speech[Math.floor(speech.length * 0.2)], hi = speech[Math.floor(speech.length * 0.95)];
  return db.map((v) => (v < -50 ? 0 : Math.max(0, Math.min(9, Math.round(((v - lo) / Math.max(6, hi - lo)) * 9)))));
}

const voiceJson = {}, lip = {};
let made = 0;
for (const line of story.lines) {
  const v = { ...story.voices[line.who] };
  if (line.speed) v.speed = line.speed;
  const wav = path.join(outDir, `${line.id}.wav`), sig = path.join(outDir, `${line.id}.sig`);
  const want = `${v.voice}|${v.speed}|${line.text}`;
  if (!existsSync(wav) || !existsSync(sig) || readFileSync(sig, "utf8") !== want) {
    const r = spawnSync(process.execPath, [TTS, line.text, "-o", wav, `--voice=${v.voice}`, `--speed=${v.speed}`], { encoding: "utf8" });
    if (r.status !== 0 || !existsSync(wav)) { console.error(r.stdout, r.stderr); throw new Error(`TTS failed for ${line.id}`); }
    writeFileSync(sig, want);
    made++;
  }
  const x = pcm(wav);
  const d = Math.round((x.length / RATE) * 1000) / 1000;
  const env = envelope(x);
  voiceJson[line.id] = { who: line.who, d, text: line.text };
  lip[line.id] = { d, env: env.join("") };
  console.log(`  ${line.id.padEnd(6)} ${line.who.padEnd(6)} ${d.toFixed(2)} s  ${line.text}`);
}
writeFileSync(path.join(ROOT, "story", "voice.json"), JSON.stringify(voiceJson, null, 2) + "\n");
writeFileSync(path.join(outDir, "lipsync.js"), "/* generated by build/voice.mjs — do not edit */\nwindow.HKLip = " + JSON.stringify(lip) + ";\n");
const total = Object.values(voiceJson).reduce((a, b) => a + b.d, 0);
console.log(`voice: ${story.lines.length} lines (${made} newly made), ${total.toFixed(1)} s of audio incl. padding`);
